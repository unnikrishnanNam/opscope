// The line weight on screen, in px, whatever the icon's size. Lucide draws
// 2 units on a 24-unit grid, which is only 1.33 px at 16 px and reads as thin.
const STROKE_PX = 1.6;

function Icon({ size = 16, children, ...props }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={(STROKE_PX * 24) / size}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

